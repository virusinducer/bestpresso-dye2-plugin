import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { replaceOnce } from '../../scripts/lib/patch.mjs'

// OLED look for the DYE2 pages: the same jet black / #cbcb13 look as the skin's OLED setting.
// bp-look.js sets <html data-bp-look> from ?look= (passed by the skin's button) or the remembered choice;
// bp-oled.css only applies under data-bp-look="oled", so "classic" stays exactly the Bestpresso green look.
//
// To switch it off, delete this file plus assets/dye2/bp-look.js and bp-oled.css.
export function apply({ root, repoRoot }) {
  const read = (name) => readFileSync(join(repoRoot, 'assets', 'dye2', name), 'utf8')
  const src = join(root, 'dye2-plugin', 'src')
  writeFileSync(
    join(src, 'utils', 'bp-oled.ts'),
    `// Generated by bestpresso-dye2-plugin. Do not edit.\nexport const bpOledCss = ${JSON.stringify(read('bp-oled.css'))};\nexport const bpLookScript = ${JSON.stringify(read('bp-look.js'))};\n`,
  )
  const shell = join(src, 'utils', 'dev-shell.ts')
  replaceOnce(shell, 'import { bpPhoneCss, bpPhoneScript } from "./bp-phone";', 'import { bpPhoneCss, bpPhoneScript } from "./bp-phone";\nimport { bpOledCss, bpLookScript } from "./bp-oled";', 'oled import')
  replaceOnce(shell, '<style>${bpPhoneCss}</style>\n</head>', '<style>${bpPhoneCss}</style>\n  <style>${bpOledCss}</style>\n</head>', 'oled css')
  replaceOnce(shell, '<script>${bpPhoneScript}</script>', '<script>${bpLookScript}</script>\n  <script>${bpPhoneScript}</script>', 'oled script')
  // Plot colours: the pressure trace takes the accent, like the skin's chart.
  replaceOnce(
    join(src, 'utils', 'chart.ts'),
    'function chartColors() { return chartIsDark() ? CHART_COLORS_DARK : CHART_COLORS_LIGHT; }',
    "var CHART_COLORS_OLED = Object.assign({}, CHART_COLORS_LIGHT, { pressure: '#cbcb13', targetPressure: '#7a7a10' });\nfunction chartColors() {\n  if (document.documentElement.getAttribute('data-bp-look') === 'oled') return CHART_COLORS_OLED;\n  return chartIsDark() ? CHART_COLORS_DARK : CHART_COLORS_LIGHT;\n}",
    'chart colours',
  )
}
