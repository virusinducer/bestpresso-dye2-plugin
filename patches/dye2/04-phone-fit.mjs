import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { replaceOnce } from '../../scripts/lib/patch.mjs'

// Phone fit for the DYE2 pages. Without the two classes bp-phone.js sets (portrait width <= 520px,
// landscape height <= 500px) nothing here applies, so tablets keep the stock 1920x1200 canvas.
//
// To switch it off, delete this file plus assets/dye2/bp-phone.{js,css}.
export function writePhoneAssets({ root, repoRoot }) {
  const read = (name) => readFileSync(join(repoRoot, 'assets', 'dye2', name), 'utf8')
  writeFileSync(
    join(root, 'dye2-plugin', 'src', 'utils', 'bp-phone.ts'),
    `// Generated by bestpresso-dye2-plugin. Do not edit.\nexport const bpPhoneCss = ${JSON.stringify(read('bp-phone.css'))};\nexport const bpPhoneScript = ${JSON.stringify(read('bp-phone.js'))};\n`,
  )
}

export function apply(context) {
  const { root } = context
  writePhoneAssets(context)
  const shell = join(root, 'dye2-plugin', 'src', 'utils', 'dev-shell.ts')
  replaceOnce(
    shell,
    'import { bpSliderCss, bpSliderScript } from "./bp-slider";',
    'import { bpSliderCss, bpSliderScript } from "./bp-slider";\nimport { bpPhoneCss, bpPhoneScript } from "./bp-phone";',
    'phone import',
  )
  replaceOnce(
    shell,
    '<style>${bpSliderCss}</style>\n</head>',
    '<style>${bpSliderCss}</style>\n  <style>${bpPhoneCss}</style>\n</head>',
    'phone css',
  )
  // The phone script defines window.__bpPhoneFit; the stock fit asks it first and falls through when it returns 0.
  replaceOnce(
    shell,
    '<script>${fitScript}</script>\n  <script>${bpSliderScript}</script>',
    '<script>${bpPhoneScript}</script>\n  <script>${fitScript}</script>\n  <script>${bpSliderScript}</script>',
    'phone script',
  )
  replaceOnce(
    shell,
    '  function fit(vw, vh) {\n',
    '  function fit(vw, vh) {\n    var phoneScale = window.__bpPhoneFit ? window.__bpPhoneFit(vw, vh) : 0;\n    if (phoneScale) { lastSy = phoneScale; return; }\n',
    'phone fit hook',
  )
}
