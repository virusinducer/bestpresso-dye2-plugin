import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { replaceOnce } from '../../scripts/lib/patch.mjs'

// Serves assets/plugin/bestpresso-button.js at /plugins/dye2.reaplugin/bestpresso-button.
export function apply({ root, repoRoot, pluginVersion }) {
  const script = readFileSync(join(repoRoot, 'assets', 'plugin', 'bestpresso-button.js'), 'utf8')
    .replace('__PLUGIN_VERSION__', pluginVersion)
  const src = join(root, 'dye2-plugin', 'src')
  writeFileSync(
    join(src, 'utils', 'bestpresso-button.ts'),
    `// Generated by bestpresso-dye2-plugin. Do not edit.
const SCRIPT = ${JSON.stringify(script)};

export function renderBestpressoButton(request: HttpRequest): HttpResponse {
  return {
    requestId: request.requestId,
    status: 200,
    headers: { "Content-Type": "application/javascript; charset=utf-8", "Cache-Control": "no-cache" },
    body: SCRIPT,
  };
}
`,
  )
  const plugin = join(src, 'plugin.ts')
  // Anchor on lines that do not depend on DYE2's chart library (Plotly became ECharts in v0.1.33).
  replaceOnce(
    plugin,
    '/// <reference path="./host.d.ts" />\n',
    '/// <reference path="./host.d.ts" />\nimport { renderBestpressoButton } from "./utils/bestpresso-button";\n',
    'host.d.ts reference',
  )
  replaceOnce(
    plugin,
    '        case "skin":\n',
    '        case "bestpresso-button":\n          return renderBestpressoButton(request);\n\n        case "skin":\n',
    'skin case',
  )
}
