import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { replaceOnce } from '../../scripts/lib/patch.mjs'

// Bestpresso look for DYE2: colour/markup edits (rules derived by tools/derive-restyle.py), a
// Bestpresso-look CSS block, the value slider, the basket carry-over and the +/- slider hook.
export function apply({ root, repoRoot }) {
  const assets = join(repoRoot, 'assets', 'dye2')
  const read = (name) => readFileSync(join(assets, name), 'utf8')
  const src = join(root, 'dye2-plugin', 'src')

  // 1. Small anchored edits (each anchor must match exactly once).
  // DYE2 v0.1.24 and later ship a dark mode: colours became theme tokens, so a rule can carry
  // find_themed (same edit, anchored on the token text), skip_themed (upstream's token covers it)
  // or only_themed (an edit that only exists in the themed source). This fork stays light-themed
  // and applies its own look on top, so upstream's dark mode is switched off below.
  const themed = existsSync(join(src, 'utils', 'theme.ts'))
  const rules = JSON.parse(read('restyle.rules.json'))
  for (const [i, rule] of rules.entries()) {
    if (themed ? rule.skip_themed : rule.only_themed) continue
    let find = themed && rule.find_themed ? rule.find_themed : rule.find
    let replace = rule.replace
    let file = join(root, rule.file)
    const has = (f, text) => readFileSync(f, 'utf8').includes(text)
    // alts: edits for when upstream reworded the anchor line (first one present wins).
    if (!has(file, find)) {
      const alt = (rule.alts || []).find((a) => has(file, a.find))
      if (alt) ({ find, replace } = alt)
    }
    // skip_if_absent: upstream removed the thing this rule restyled (its new look already fits).
    if (rule.skip_if_absent && !has(file, find)) continue
    // moved_to: DYE2 v0.1.26 moved shared CSS (picker styles, fav-number buttons) into
    // shared-components.ts. If the anchor is gone from its old file, apply the rule at the new
    // home; if an earlier rule already applied the identical edit there, there is nothing to do.
    if (rule.moved_to && !has(file, find)) {
      file = join(root, rule.moved_to)
      if (!has(file, find) && has(file, replace)) continue
    }
    replaceOnce(file, find, replace, `restyle rule ${i} (${rule.file})`)
  }
  if (themed) {
    replaceOnce(
      join(src, 'utils', 'theme.ts'),
      "    theme: param || remote || cached || 'light',",
      "    theme: 'light', // dark mode switched off in this fork",
      'upstream dark mode off',
    )
    // Upstream's test asserts that ?theme=dark wins, which is exactly what is switched off here.
    // package.json lists the file by name, so it is stubbed rather than deleted.
    writeFileSync(
      join(root, 'dye2-plugin', 'test', 'theme.test.mjs'),
      "// Stubbed by bestpresso-dye2-plugin: upstream's dark mode is switched off in this fork.\nconsole.log('theme tests skipped (dark mode off)');\n",
    )
  }

  // 2. Bestpresso-look CSS, appended to the shell's variable/fallback stylesheet.
  const focusRule = themed
    ? '    .re-input-row:focus-within .re-input { color: var(--input-text); }'
    : '    .re-input-row:focus-within .re-input { color: #111; }'
  replaceOnce(
    join(src, 'utils', 'dev-shell.ts'),
    `${focusRule}\n  \`;\n}`,
    `${focusRule}\n${read('bp-look.css')}  \`;\n}`,
    'cssVarFallbacks end',
  )

  // 3. Slider assets and their place in the page shell.
  writeFileSync(
    join(src, 'utils', 'bp-slider.ts'),
    `// Generated by bestpresso-dye2-plugin. Do not edit.\nexport const bpSliderCss = ${JSON.stringify(read('bp-slider.css'))};\nexport const bpSliderScript = ${JSON.stringify(read('bp-slider.js'))};\n`,
  )
  const shell = join(src, 'utils', 'dev-shell.ts')
  replaceOnce(
    shell,
    'import tailwindCss from "../styles/tailwind.generated.css?inline";',
    'import tailwindCss from "../styles/tailwind.generated.css?inline";\nimport { bpSliderCss, bpSliderScript } from "./bp-slider";',
    'shell import',
  )
  replaceOnce(
    shell,
    '<style>${cssVarFallbacks()}${styles}</style>\n</head>',
    '<style>${cssVarFallbacks()}${styles}</style>\n  <style>${bpSliderCss}</style>\n</head>',
    'shell slider css',
  )
  replaceOnce(
    shell,
    '<script>${fitScript}</script>\n  ${scripts',
    '<script>${fitScript}</script>\n  <script>${bpSliderScript}</script>\n  ${scripts',
    'shell slider script',
  )

  // 4. Tap-a-number opens the slider (falls back to the original editor).
  const head = 'function makeValueEditable(valueId, min, max, formatter, onChange) {\n'
  for (const page of ['dashboard.ts', 'edit-shot.ts']) {
    replaceOnce(join(src, 'pages', page), head, head + read('make-value-editable.js'), `makeValueEditable in ${page}`)
  }

  // 5. Carry the basket chosen for the shot into its annotations.
  const subtitle = "  set('es-shot-subtitle', full + (profile.title ? '  •  ' + profile.title : ''));"
  replaceOnce(join(src, 'pages', 'edit-shot.ts'), subtitle, read('basket-seed.js') + subtitle, 'basket carry-over')

  // 6. Segmented control: dark text on the green segment.
  replaceOnce(
    join(src, 'utils', 'shared-components.ts'),
    'background:var(--mimoja-blue);color:#fff;',
    'background:var(--mimoja-blue);color: var(--dye-on-accent);',
    'segmented control colour',
  )
}
